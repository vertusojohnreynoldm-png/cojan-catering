<?php

namespace App\Console\Commands;

use App\Services\ServiceArea;
use Illuminate\Console\Command;
use Illuminate\Support\Facades\Http;
use Illuminate\Support\Sleep;

/**
 * ONE-TIME data generator — run locally, commit the result. Never called
 * at runtime: the app reads the static file it writes
 * (database/data/barangay_coords.php) and makes no Nominatim calls.
 *
 * Looks up the San Jose, Occidental Mindoro boundary and every deliverable
 * San Jose barangay on OpenStreetMap's Nominatim, following its usage
 * policy (https://operations.osmfoundation.org/policies/nominatim/):
 * an identifying User-Agent, at most 1 request per second, no bulk/
 * repeated runs. Barangays it can't place inside San Jose are written as
 * null and fall back to the town centre in App\Services\DeliveryLocation.
 */
class FetchBarangayCoords extends Command
{
    protected $signature = 'geo:fetch-barangay-coords {--dry-run : Print results without writing the file}';

    protected $description = 'One-time: look up San Jose barangay centres on Nominatim and write database/data/barangay_coords.php';

    private const ENDPOINT = 'https://nominatim.openstreetmap.org/search';
    private const USER_AGENT = 'CojanCatering/1.0 (BSIT capstone; +https://cojan-catering-production.up.railway.app)';
    private const PAUSE_MICROSECONDS = 1_100_000; // a little over 1 request/second

    public function handle(): int
    {
        $town = $this->search('San Jose, Occidental Mindoro, Philippines');
        if (!$town || empty($town['boundingbox'])) {
            $this->error('Could not find the San Jose boundary — nothing written.');

            return self::FAILURE;
        }

        [$south, $north, $west, $east] = array_map('floatval', $town['boundingbox']);
        $townCenter = [round((float) $town['lat'], 7), round((float) $town['lon'], 7)];
        $this->info("San Jose boundary: lat {$south}..{$north}, lng {$west}..{$east}; centre " . implode(', ', $townCenter));

        $coords = [];
        $fellBack = [];

        foreach (ServiceArea::menuBarangays() as $barangay) {
            Sleep::usleep(self::PAUSE_MICROSECONDS);

            $hit = $this->search("{$barangay}, San Jose, Occidental Mindoro, Philippines");
            $point = $hit ? [round((float) $hit['lat'], 7), round((float) $hit['lon'], 7)] : null;

            // Only accept an actual sub-municipal place inside San Jose's box —
            // Nominatim answers an unknown barangay with the town itself (or
            // something elsewhere), which would be worse than the honest fallback.
            $isTownItself = $hit && in_array($hit['addresstype'] ?? '', ['town', 'city', 'municipality', 'county', 'state', 'region'], true);
            $inside = $point && $point[0] >= $south && $point[0] <= $north && $point[1] >= $west && $point[1] <= $east;

            if ($point && $inside && !$isTownItself) {
                $coords[$barangay] = $point;
                $this->line("  ✓ {$barangay}: {$point[0]}, {$point[1]} ({$hit['addresstype']})");
            } else {
                $coords[$barangay] = null;
                $fellBack[] = $barangay;
                $this->warn("  – {$barangay}: not found → town centre");
            }
        }

        $data = [
            'generated_at' => now()->toDateTimeString(),
            'source'       => 'OpenStreetMap Nominatim (© OpenStreetMap contributors, ODbL) via php artisan geo:fetch-barangay-coords',
            'town_center'  => $townCenter,
            // San Jose's OSM administrative boundary box, unpadded — padding
            // is applied in App\Services\DeliveryLocation.
            'bounds'       => ['south' => $south, 'north' => $north, 'west' => $west, 'east' => $east],
            'barangays'    => $coords,
        ];

        $this->newLine();
        $this->info(count($coords) - count($fellBack) . ' of ' . count($coords) . ' barangays found.');
        if ($fellBack) {
            $this->warn('Fell back to the town centre: ' . implode(', ', $fellBack));
        }

        if ($this->option('dry-run')) {
            return self::SUCCESS;
        }

        $php = "<?php\n\n"
            . "/**\n"
            . " * GENERATED by `php artisan geo:fetch-barangay-coords` — do not edit by hand.\n"
            . " * Approximate centres of the deliverable San Jose, Occidental Mindoro\n"
            . " * barangays (null = not found; App\\Services\\DeliveryLocation falls back to\n"
            . " * the town centre). Read at runtime instead of calling Nominatim.\n"
            . " */\n\n"
            . 'return ' . var_export($data, true) . ";\n";

        file_put_contents(database_path('data/barangay_coords.php'), $php);
        $this->info('Wrote database/data/barangay_coords.php');

        return self::SUCCESS;
    }

    private function search(string $query): ?array
    {
        $response = Http::withHeaders(['User-Agent' => self::USER_AGENT, 'Accept-Language' => 'en'])
            ->timeout(20)
            ->get(self::ENDPOINT, [
                'q'            => $query,
                'format'       => 'jsonv2',
                'limit'        => 1,
                'countrycodes' => 'ph',
            ]);

        if (!$response->successful()) {
            $this->warn("  Nominatim HTTP {$response->status()} for \"{$query}\"");

            return null;
        }

        return $response->json()[0] ?? null;
    }
}
